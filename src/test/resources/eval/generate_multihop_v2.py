PERIODS = [
    (24, 12, 12), (36, 12, 24), (48, 24, 24), (36, 18, 24),
    (24, 24, 12), (60, 24, 36), (12, 12, 6), (36, 24, 12),
]

PREFIX = {
    "会议设备": "HY", "办公家具": "JJ", "厨房电器": "CF", "安防设备": "AF",
    "环境设备": "HJ", "清洁设备": "QJ", "培训设备": "PX", "仓储设备": "CC",
    "前台设备": "QT",
}


def periods_of(tag: str):
    h = hashlib.sha256(f"{SEED}:{tag}".encode()).hexdigest()
    return PERIODS[int(h[:8], 16) % len(PERIODS)]


def build():
    rng = random.Random(SEED)
    assets = []   # (品类, 名称, 部门, 资产编号)
    for i, (cat, name, dep) in enumerate(NEW_ASSETS, 1):
        tag = f"YC-{PREFIX[cat]}-2026-{i:04d}"
        assets.append((cat, name, dep, tag))

    # 历史资产（登记表干扰行）：只进登记表，不进配发通知
    hist = []
    for i in range(1, 371):
        cat = rng.choice(list(PREFIX))
        tag = f"YC-{PREFIX[cat]}-{rng.choice([2022, 2023, 2024, 2025])}-{i:04d}"
        hist.append(tag)

    # A. 配发通知（桥接文档：名称 → 编号）
    lines = [f"{i}. {cat}：{name}，配发{dep}，资产编号 {tag}。"
             for i, (cat, name, dep, tag) in enumerate(assets, 1)]
    notice = f"""# 2026 年新增办公设备配发通知

> 适用范围：北京总部及各子公司。

（云启科技 · 2026 年 4 月 2 日 · 行政部）

## 一、通知背景

公司于 2026 年第一季度完成一批办公设备采购，现将新增设备的品类、名称、
配发部门与**资产编号**公布如下，请各部门据此办理领用登记。

## 二、新增设备与资产编号

{chr(10).join(lines)}

## 三、领用与登记

各部门负责人应于 2026 年 4 月 20 日前完成领用登记。
设备保修期自领用登记之日起算；**各资产的具体保修期限见《固定资产保修期限登记表》**，
以资产编号为准查询，本通知不列出具体期限。

## 四、注意事项

资产编号是设备在固定资产系统中的唯一标识，报修、盘点、移交均需提供资产编号。
未在名单中的历史设备，其资产编号与保修期限同样以《固定资产保修期限登记表》为准。
"""

    # B. 保修期限登记表（大表：目标行只是其中一行）
    rows = [f"{tag} | 整机 {p[0]} 个月 | 电池 {p[1]} 个月 | 屏幕 {p[2]} 个月"
            for tag in hist for p in [periods_of(tag)]]
    new_rows = [f"{tag} | 整机 {periods_of(tag)[0]} 个月 | 电池 {periods_of(tag)[1]} 个月 | 屏幕 {periods_of(tag)[2]} 个月"
                for _, _, _, tag in assets]
    all_rows = sorted(set(rows + new_rows))
    register = f"""# 固定资产保修期限登记表

> 适用范围：北京总部及各子公司。

（云启科技 · 2026 年 4 月 2 日 · 行政部 · 信息技术部）

## 一、说明

本表按**资产编号**逐台登记保修期限，是设备保修状态的唯一依据。
查询时请先确认设备资产编号（见《2026 年新增办公设备配发通知》或固定资产系统），
再按编号检索本表对应行。不同资产的期限不得相互比照适用。

## 二、保修期限明细

资产编号 | 整机 | 电池 | 屏幕
--- | --- | --- | ---
{chr(10).join(all_rows)}

## 三、说明事项

1. 保修期自领用登记之日起算；
2. 超出保修期限的维修按有偿服务处理；
3. 本表由信息技术部维护，每月更新一次。
"""
    return notice, register, assets, all_rows


