def main():
    OUT.mkdir(parents=True, exist_ok=True)
    notice, register, assets, all_rows = build()
    (OUT / "N00-2026年新增办公设备配发通知.md").write_text(notice, encoding="utf-8")
    (OUT / "N01-固定资产保修期限登记表.md").write_text(register, encoding="utf-8")
    for name, text in MISC.items():
        (OUT / f"Z-{name}").write_text(text, encoding="utf-8")

    print(f"生成完成: {OUT}")
    print(f"  配发通知 1 篇（{len(assets)} 个新资产，含名称↔编号映射）")
    print(f"  保修登记表 1 篇（{len(all_rows)} 行）")
    print(f"  管理办法 {len(MISC)} 篇")
    print(f"  合计 {2 + len(MISC)} 篇")
    print("\n新资产与期限（前 10，供出题用）：")
    for cat, name, dep, tag in assets[:10]:
        p = periods_of(tag)
        print(f"  {tag}  {name}  ({dep})  整机{p[0]}/电池{p[1]}/屏幕{p[2]} 个月")


if __name__ == "__main__":
    main()
