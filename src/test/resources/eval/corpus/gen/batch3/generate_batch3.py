def main():
    OUT.mkdir(parents=True, exist_ok=True)
    n = 0
    for (no, title, org, scope, sections) in E_SPECS:
        p = OUT / f"E{no}-{title}.md"
        p.write_text(render_e(no, title, org, scope, sections), encoding="utf-8")
        n += 1
    for fname, content in F_DOCS.items():
        (OUT / fname).write_text(content, encoding="utf-8")
        n += 1
    total_chars = {f.name: len(f.read_text(encoding="utf-8")) for f in sorted(OUT.glob("*.md"))}
    longs = {k: v for k, v in total_chars.items() if k.startswith("F0")}
    print(f"generated {n} docs -> {OUT}")
    for k, v in longs.items():
        print(f"  {k}: {v} chars ≈ {v//400} chunks")

if __name__ == "__main__":
    main()
