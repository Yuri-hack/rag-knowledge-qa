def render_long(title, org, scope, sections):
    lines = [f"# {title}", "", f"> 适用范围：{scope}。", "", f"（{org}）", ""]
    for i, (h, paras) in enumerate(sections, 1):
        cn = "一二三四五六七八九十"[i-1] if i <= 10 else str(i)
        lines.append(f"## {cn}、{h}")
        lines.append("")
        for p in paras:
            lines.append(p)
            lines.append("")
    return "\n".join(lines)


